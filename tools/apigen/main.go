// Command apigen generates internal/api from the operations the hand-written
// commands call. Generate works from the committed spec snapshot, so its output
// only changes when the snapshot, operations.txt, or this tool changes. It is a
// separate module so the code generator stays out of the CLI's dependencies.
//
//	go run .           regenerate internal/api/api.gen.go from the snapshot
//	go run . -update   refresh the snapshot from the prod spec, then regenerate
package main

import (
	"bytes"
	_ "embed"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"log"
	"maps"
	"net/http"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
	"github.com/oapi-codegen/oapi-codegen/v2/pkg/codegen"
)

const specURL = "https://api.cloud.wherobots.com/openapi.json"

//go:embed operation.tmpl
var operationTemplate string

// The stock header embeds the tool's build version, which varies by machine.
const headerTemplate = `// Code generated by tools/apigen from openapi.snapshot.json. DO NOT EDIT.

package {{.PackageName}}
`

type object = map[string]any

func main() {
	update := flag.Bool("update", false, "refresh the snapshot from the prod spec first")
	dir := flag.String("dir", "../../internal/api", "directory holding operations.txt and the generated files")
	flag.Parse()

	if err := run(*dir, *update); err != nil {
		log.Fatal(err)
	}
}

func run(dir string, update bool) error {
	wanted, err := readOperations(filepath.Join(dir, "operations.txt"))
	if err != nil {
		return err
	}
	snapshotPath := filepath.Join(dir, "openapi.snapshot.json")
	if update {
		if err := refreshSnapshot(snapshotPath, wanted); err != nil {
			return err
		}
	}
	raw, err := os.ReadFile(snapshotPath)
	if err != nil {
		return err
	}
	var snapshot object
	if err := json.Unmarshal(raw, &snapshot); err != nil {
		return fmt.Errorf("parse %s: %w", snapshotPath, err)
	}
	if err := checkSnapshot(snapshot, wanted); err != nil {
		return err
	}
	code, err := generate(snapshot, wanted)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "api.gen.go"), code, 0o644)
}

// readOperations maps each listed operationId to its response schema override,
// which is usually empty.
func readOperations(path string) (map[string]string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	wanted := map[string]string{}
	for line := range strings.Lines(string(raw)) {
		fields := strings.Fields(line)
		if len(fields) == 0 || strings.HasPrefix(fields[0], "#") {
			continue
		}
		wanted[fields[0]] = strings.Join(fields[1:], "")
	}
	return wanted, nil
}

func refreshSnapshot(path string, wanted map[string]string) error {
	resp, err := http.Get(specURL)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("GET %s: %s", specURL, resp.Status)
	}
	raw, err := io.ReadAll(resp.Body)
	if err != nil {
		return err
	}
	var full object
	if err := json.Unmarshal(raw, &full); err != nil {
		return fmt.Errorf("parse %s: %w", specURL, err)
	}
	filtered, err := filterSpec(full, wanted)
	if err != nil {
		return err
	}
	var out bytes.Buffer
	enc := json.NewEncoder(&out)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(filtered); err != nil {
		return err
	}
	return os.WriteFile(path, out.Bytes(), 0o644)
}

// filterSpec keeps the wanted operations and the schemas they reach. It changes
// nothing else, so the snapshot stays a faithful subset of the prod spec.
func filterSpec(full object, wanted map[string]string) (object, error) {
	kept := object{}
	found := map[string]bool{}
	eachOperation(full, func(id, path, method string, op object) {
		if _, ok := wanted[id]; !ok {
			return
		}
		found[id] = true
		if kept[path] == nil {
			kept[path] = object{}
		}
		kept[path].(object)[method] = op
	})
	var missing []string
	for id := range wanted {
		if !found[id] {
			missing = append(missing, id)
		}
	}
	if len(missing) > 0 {
		slices.Sort(missing)
		return nil, fmt.Errorf("spec has no operation %s", strings.Join(missing, ", "))
	}

	components, _ := full["components"].(object)
	schemas, _ := components["schemas"].(object)
	reached := object{}
	var reach func(node any)
	reach = func(node any) {
		switch v := node.(type) {
		case object:
			for key, value := range v {
				if ref, ok := value.(string); ok && key == "$ref" {
					name := strings.TrimPrefix(ref, "#/components/schemas/")
					if _, seen := reached[name]; !seen {
						reached[name] = schemas[name]
						reach(schemas[name])
					}
					continue
				}
				reach(value)
			}
		case []any:
			for _, item := range v {
				reach(item)
			}
		}
	}
	reach(kept)

	return object{
		"openapi":    full["openapi"],
		"info":       full["info"],
		"paths":      kept,
		"components": object{"schemas": reached},
	}, nil
}

// checkSnapshot catches an operations.txt edit that was not followed by
// -update, which would otherwise pass CI with stale output.
func checkSnapshot(snapshot object, wanted map[string]string) error {
	have := map[string]bool{}
	eachOperation(snapshot, func(id, _, _ string, _ object) { have[id] = true })
	var stale []string
	for id := range wanted {
		if !have[id] {
			stale = append(stale, "missing "+id)
		}
	}
	for id := range have {
		if _, ok := wanted[id]; !ok {
			stale = append(stale, "unlisted "+id)
		}
	}
	if len(stale) > 0 {
		slices.Sort(stale)
		return fmt.Errorf("snapshot is out of date (%s): run make update-spec", strings.Join(stale, ", "))
	}
	return nil
}

func eachOperation(doc object, visit func(id, path, method string, op object)) {
	for path, item := range doc["paths"].(object) {
		for method, value := range item.(object) {
			if op, ok := value.(object); ok && op["operationId"] != nil {
				visit(op["operationId"].(string), path, method, op)
			}
		}
	}
}

// generate runs oapi-codegen, models only: the executor already builds requests
// with auth, retries and dry-run, and the generated client would add a runtime
// dependency.
func generate(snapshot object, wanted map[string]string) ([]byte, error) {
	codegen.TemplateFunctions["responseType"] = responseType
	doc := downgrade(snapshot, wanted)
	raw, err := json.Marshal(doc)
	if err != nil {
		return nil, err
	}
	loaded, err := openapi3.NewLoader().LoadFromData(raw)
	if err != nil {
		return nil, fmt.Errorf("load downgraded spec: %w", err)
	}
	code, err := codegen.Generate(loaded, codegen.Configuration{
		PackageName: "api",
		Generate:    codegen.GenerateOptions{Models: true},
		Compatibility: codegen.CompatibilityOptions{
			AlwaysPrefixEnumValues: true,
		},
		OutputOptions: codegen.OutputOptions{
			NameNormalizer: string(codegen.NameNormalizerFunctionToCamelCaseWithInitialisms),
			// Union members are referenced by nothing once unions are `any`.
			SkipPrune: true,
			UserTemplates: map[string]string{
				"imports.tmpl":        headerTemplate,
				"request-bodies.tmpl": operationTemplate,
			},
			TypeMapping: &codegen.TypeMapping{
				// float32 would round metric values.
				Number: codegen.FormatMapping{Default: codegen.SimpleTypeSpec{Type: "float64"}},
				// Commands print timestamps as the API sent them.
				String: codegen.FormatMapping{Formats: map[string]codegen.SimpleTypeSpec{
					"date-time": {Type: "string"},
				}},
			},
		},
	})
	if err != nil {
		return nil, err
	}
	return []byte(code), nil
}

// downgrade rewrites the snapshot's FastAPI-flavoured OpenAPI 3.1 into the 3.0
// oapi-codegen understands. It works on a copy; the result is never committed.
func downgrade(snapshot object, wanted map[string]string) object {
	raw, _ := json.Marshal(snapshot)
	var doc object
	_ = json.Unmarshal(raw, &doc)

	doc["openapi"] = "3.0.3"
	eachOperation(doc, func(id, _, _ string, op object) {
		schema := wanted[id]
		if schema == "" {
			return
		}
		content := op["responses"].(object)["200"].(object)["content"].(object)["application/json"].(object)
		content["schema"] = object{"$ref": "#/components/schemas/" + schema}
	})
	simplify(doc)
	return doc
}

// simplify removes the 3.1 constructs oapi-codegen would reject or turn into
// union types, which import github.com/oapi-codegen/runtime.
func simplify(node any) {
	switch v := node.(type) {
	case []any:
		for _, item := range v {
			simplify(item)
		}
	case object:
		for _, value := range v {
			simplify(value)
		}
		if branches, ok := v["anyOf"].([]any); ok {
			collapseUnion(v, branches)
		}
		delete(v, "propertyNames")
		// 3.0 forbids siblings of $ref.
		if ref, ok := v["$ref"]; ok {
			clear(v)
			v["$ref"] = ref
		}
	}
}

// collapseUnion turns `anyOf: [X, null]` into a nullable X. A union of several
// real branches becomes an untyped schema: the CLI never reads those fields.
func collapseUnion(schema object, branches []any) {
	delete(schema, "anyOf")
	var solid []object
	for _, branch := range branches {
		if b := branch.(object); b["type"] != "null" {
			solid = append(solid, b)
		}
	}
	if len(solid) != 1 {
		return
	}
	maps.Copy(schema, solid[0])
	if len(branches) > 1 {
		schema["nullable"] = true
	}
}

// responseType is the Go type an operation's success body decodes to.
func responseType(op codegen.OperationDefinition) (string, error) {
	definitions, err := op.GetResponseTypeDefinitions()
	if err != nil {
		return "", err
	}
	for _, definition := range definitions {
		if strings.HasPrefix(definition.ResponseName, "2") && definition.ContentTypeName == "application/json" {
			return definition.Schema.TypeDecl(), nil
		}
	}
	return "struct{}", nil
}
